#!/usr/bin/env node
/* build-dataset.js — 瘦身打包：raw 数据 → data/exercises-dataset.js
   输入: data/raw/exercises.json, data/raw/name_zh.json, data/action-map.json(可选)
   输出: data/exercises-dataset.js (window.EX_DATASET)
   用法: node scripts/build-dataset.js */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const RAW = path.join(ROOT, 'data', 'raw');
const OUT = path.join(ROOT, 'page', 'data', 'exercises-dataset.js');
const AMAP = path.join(ROOT, 'data', 'action-map.json');

const raw = JSON.parse(fs.readFileSync(path.join(RAW, 'exercises.json'), 'utf8'));
const zh = JSON.parse(fs.readFileSync(path.join(RAW, 'name_zh.json'), 'utf8'));
const amap = fs.existsSync(AMAP) ? JSON.parse(fs.readFileSync(AMAP, 'utf8')) : {};

const ATTR = '© Gym visual — https://gymvisual.com/';
const noZhNames = [];

// 压缩说明文本: 合并空白
function squeeze(s) {
  return String(s || '').replace(/\s+/g, ' ').trim();
}

const items = raw.map(function(e) {
  const z = zh[e.name] || e.name;
  if (!zh[e.name]) noZhNames.push(e.id + ' ' + e.name);
  const steps = (e.instruction_steps && e.instruction_steps.zh) || [];
  return {
    id: e.id,
    name: e.name,
    zh: z,
    cat: e.category,
    eq: e.equipment,
    target: e.target,
    mg: e.muscle_group,
    sec: e.secondary_muscles || [],
    img: e.image || null,
    gif: e.gif_url || null,
    mid: e.media_id,
    ins: squeeze(e.instructions && e.instructions.zh),
    steps: steps.map(squeeze)
  };
});

const byId = {};
items.forEach(function(i){ byId[i.id] = i; });

// 校验 action-map 的 dsId 均存在（过滤注释键）
Object.keys(amap).forEach(function(k){
  if (k.charAt(0) === '_') { delete amap[k]; return; }
  if (amap[k] && !byId[amap[k]]) {
    console.error('[warn] action-map dsId 不存在:', k, '->', amap[k]);
    delete amap[k];
  }
});

// 紧凑数组格式: [id, name, zh, cat, eq, target, mg, sec[], img, gif, mid, ins, steps[]]
// 键序由 window.EX_DATASET_KEYS 约定，省去每条重复的 JSON 键名字符串
const KEYS = ['id','name','zh','cat','eq','target','mg','sec','img','gif','mid','ins','steps'];

const rows = items.map(function(i) {
  return [i.id, i.name, i.zh, i.cat, i.eq, i.target, i.mg, i.sec, i.img, i.gif, i.mid, i.ins, i.steps];
});

const payload = {
  v: 1,
  attribution: ATTR,
  updated: new Date().toISOString().slice(0, 10),
  keys: KEYS,
  aliases: amap,
  items: rows
};

const js = '/* generated by scripts/build-dataset.js — do not edit */\n'
  + 'window.EX_DATASET = ' + JSON.stringify(payload) + ';\n';

fs.writeFileSync(OUT, js);
const kb = (Buffer.byteLength(js) / 1024).toFixed(1);
// 中文文本 gzip 比率约 3.2:1 — 用 zlib 实测传输体积
const gz = require('zlib').gzipSync(Buffer.from(js));
const gzkb = (gz.length / 1024).toFixed(1);

console.log('items:', items.length);
console.log('aliases:', Object.keys(amap).length);
console.log('missing zh names:', noZhNames.length, noZhNames.slice(0, 6));
console.log('size raw:', kb, 'KB | gzip(transmit):', gzkb, 'KB', gz.length <= 500 * 1024 ? '(OK ≤500KB)' : '(OVER threshold)');
